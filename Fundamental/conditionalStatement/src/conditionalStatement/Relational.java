package conditionalStatement;
import java.util.Scanner;
public class Relational {
    public static void main(String args[]){
        int a = 5, b = 10, c = 15;
        System.out.println(a < b);
        System.out.println(a < b && a < c);
        System.out.println(a < b || a < c);
    }
    
}